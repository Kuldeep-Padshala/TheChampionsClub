-- Free slots for the website, the phone, and the 6 pm rush:  SELECT * FROM fn_free_slots(current_date, current_date + 6);
CREATE OR REPLACE FUNCTION fn_free_slots(p_from date, p_to date, p_sport_id bigint DEFAULT NULL)
RETURNS TABLE (court_id bigint, court_name text, sport_id bigint, slot_start timestamptz, slot_end timestamptz)
LANGUAGE sql STABLE AS $$
    WITH cfg AS (
        SELECT COALESCE((SELECT value::int FROM club_settings WHERE key = 'session_duration_minutes'), 60) AS dur,
               COALESCE((SELECT value::int FROM club_settings WHERE key = 'slot_interval_minutes'), 30)    AS step,
               COALESCE((SELECT timezone FROM club_profile LIMIT 1), 'UTC')                                AS tz
    ),
    cand AS (
        SELECT c.id AS cid, c.name AS cname, c.sport_id AS sid,
               ((d.dt + h.open_time) AT TIME ZONE cfg.tz) + make_interval(mins => n * cfg.step) AS s,
               ((d.dt + h.open_time) AT TIME ZONE cfg.tz) + make_interval(mins => n * cfg.step + cfg.dur) AS e
          FROM cfg
         CROSS JOIN generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') AS d(dt)
          JOIN court_operating_hours h ON h.day_of_week = EXTRACT(DOW FROM d.dt)::int
          JOIN courts c ON c.id = h.court_id AND c.status = 'active'
         CROSS JOIN LATERAL generate_series(
                0, ((EXTRACT(EPOCH FROM (h.close_time - h.open_time)) / 60)::int - cfg.dur) / cfg.step
              ) AS n
         WHERE p_sport_id IS NULL OR c.sport_id = p_sport_id
    )
    SELECT cid, cname, sid, s, e
      FROM cand
     WHERE s > now()
       AND NOT EXISTS (SELECT 1 FROM court_reservations r
                        WHERE r.court_id = cand.cid AND r.status = 'active'
                          AND tstzrange(r.starts_at, r.ends_at) && tstzrange(cand.s, cand.e))
     ORDER BY s, cname;
$$;

