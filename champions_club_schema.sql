CREATE OR REPLACE FUNCTION fn_apply_stock_movement() RETURNS trigger AS $$
BEGIN
    UPDATE product_variants
       SET stock_on_hand = stock_on_hand + NEW.quantity_change
     WHERE id = NEW.variant_id
    RETURNING stock_on_hand INTO NEW.balance_after;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown variant %', NEW.variant_id;
    END IF;
    RETURN NEW;      -- a movement that would push stock below 0 fails the CHECK on product_variants
END $$ LANGUAGE plpgsql;

