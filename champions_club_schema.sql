-- A payment can never be refunded for more than it was.
CREATE OR REPLACE FUNCTION fn_refunds_before_insert() RETURNS trigger AS $$
DECLARE
    v_paid     numeric(12,2);
    v_refunded numeric(12,2);
BEGIN
    SELECT amount INTO v_paid FROM payments WHERE id = NEW.payment_id FOR UPDATE;
    SELECT COALESCE(SUM(amount), 0) INTO v_refunded FROM refunds WHERE payment_id = NEW.payment_id;
    IF v_refunded + NEW.amount > v_paid THEN
        RAISE EXCEPTION 'Refund of % exceeds the refundable balance (%) of payment %',
            NEW.amount, v_paid - v_refunded, NEW.payment_id USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_refunds_before_insert BEFORE INSERT ON refunds
    FOR EACH ROW EXECUTE FUNCTION fn_refunds_before_insert();

-- Keep invoices.amount_paid and invoices.status in line with payments and refunds.
CREATE OR REPLACE FUNCTION fn_sync_invoice_payments(p_invoice_id bigint) RETURNS void AS $$
DECLARE
    v_paid numeric(12,2);
BEGIN
    SELECT COALESCE(SUM(p.amount) FILTER (WHERE p.status = 'success'), 0)
           - COALESCE((SELECT SUM(rf.amount) FROM refunds rf
                         JOIN payments p2 ON p2.id = rf.payment_id
                        WHERE p2.invoice_id = p_invoice_id), 0)
      INTO v_paid
      FROM payments p
     WHERE p.invoice_id = p_invoice_id;

    UPDATE invoices
       SET amount_paid = v_paid,
           status = CASE WHEN status IN ('draft','void') THEN status
                         WHEN v_paid >= total_amount      THEN 'paid'
                         WHEN v_paid > 0                  THEN 'partially_paid'
                         ELSE 'issued' END
     WHERE id = p_invoice_id;
END $$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION trg_payments_sync() RETURNS trigger AS $$
BEGIN
    PERFORM fn_sync_invoice_payments(NEW.invoice_id);
    IF TG_OP = 'UPDATE' AND OLD.invoice_id <> NEW.invoice_id THEN
        PERFORM fn_sync_invoice_payments(OLD.invoice_id);
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payments_sync AFTER INSERT OR UPDATE ON payments
    FOR EACH ROW EXECUTE FUNCTION trg_payments_sync();

CREATE OR REPLACE FUNCTION trg_refunds_sync() RETURNS trigger AS $$
BEGIN
    PERFORM fn_sync_invoice_payments((SELECT invoice_id FROM payments WHERE id = NEW.payment_id));
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_refunds_sync AFTER INSERT ON refunds
    FOR EACH ROW EXECUTE FUNCTION trg_refunds_sync();

