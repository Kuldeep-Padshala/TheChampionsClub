  FROM invoice_items ii JOIN invoices i ON i.id = ii.invoice_id
 WHERE i.status NOT IN ('draft','void')
 GROUP BY i.issue_date, ii.source;

-- Owner: money actually received, per day, by cash / card / UPI / online (refunds are in the refunds table).
CREATE VIEW v_payments_by_day_method AS
SELECT (p.paid_at AT TIME ZONE COALESCE((SELECT timezone FROM club_profile LIMIT 1), 'UTC'))::date AS payment_date,
       p.method, SUM(p.amount) AS amount_received, COUNT(*) AS payment_count
  FROM payments p
 WHERE p.status = 'success'
 GROUP BY 1, 2;

-- Owner: "what do we owe?"  suppliers/bills + approved salaries not yet paid + unpaid tax.
CREATE VIEW v_amounts_owed AS
SELECT 'bill'::text AS owed_type, COALESCE(s.name, ec.name) AS owed_to, e.description, e.amount AS amount_due, e.due_date
  FROM expenses e
  JOIN expense_categories ec ON ec.id = e.category_id
  LEFT JOIN suppliers s ON s.id = e.supplier_id
 WHERE e.status = 'unpaid'
UNION ALL
SELECT 'salary', emp.full_name, 'Salary ' || to_char(pr.period_month, 'Mon YYYY'), pi.net_pay, NULL::date
  FROM payroll_items pi
  JOIN payroll_runs pr ON pr.id = pi.payroll_run_id
  JOIN employees emp ON emp.id = pi.employee_id
 WHERE pi.payment_status = 'pending' AND pr.status IN ('approved','paid')
UNION ALL
SELECT 'tax', t.tax_type, 'Return for ' || t.period_start || ' to ' || t.period_end, t.net_payable, t.due_date
  FROM tax_returns t
 WHERE t.status <> 'paid' AND t.net_payable > 0;
