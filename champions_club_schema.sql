-- =====================================================================================
--  THE CHAMPIONS CLUB  -  Sports Club Management System
--  Database schema  |  PostgreSQL 14+  |  run top to bottom on an empty database
-- =====================================================================================
--
--  ROLES (decided)
--    1 owner        2 manager (exactly ONE)   3 front_desk (also handles enquiries)
--    4 shop_staff   5 bar_staff (bar, cafe, kitchen)   6 accountant
--    7 member (Gold / Silver / Junior are PLANS, not roles)   8 system_admin
--
--  SECTIONS
--    1  Identity & access     roles, permissions, role_permissions, users, user_roles
--    2  Club profile/settings club_profile, club_settings
--    3  Staff (HR)            employees, shift_templates, shifts, attendance_records,
--                             leave_types, leave_requests, payroll_runs, payroll_items
--    4  Members & customers   guardians, membership_plans, plan_benefits, members,
--                             memberships, guests, business_clients, member_notes
--    5  Courts & bookings     sports, courts, court_operating_hours, court_rates,
--                             court_reservations, bookings, check_ins
--    6  Tax                   tax_rates
--    7  Gear shop & stock     product_categories, products, product_variants, suppliers,
--                             purchase_orders, purchase_order_items, stock_movements,
--                             shop_orders, shop_order_items
--    8  Bar & cafeteria       bar_menu_categories, bar_menu_items, dining_tables,
--                             bar_tabs, bar_orders, bar_order_items
--    9  Enquiries (CRM)       enquiries, enquiry_activities, quotes, quote_items
--    10 Finance               invoices, invoice_items, payments, refunds, daily_closings,
--                             expense_categories, expenses, tax_returns, report_shares
--    11 Notifications & audit notifications, audit_logs
--    12-15 Triggers, indexes, seed data, reporting views, availability function
--
--  CONVENTIONS
--    * ids are bigint identity. Money is numeric(12,2). Percentages are numeric(5,2) (0-100).
--    * text + CHECK (...) is used instead of ENUM so allowed values are easy to edit.
--    * Unit prices are tax-EXCLUSIVE. invoice/order line_total = qty*unit_price - discount + tax.
--    * Snapshot columns (price, discount %, rate used) are copied at the time of sale so
--      later plan or price changes never rewrite history.
--    * day_of_week: 0 = Sunday ... 6 = Saturday (same as PostgreSQL EXTRACT(DOW)).
--    * Numbers such as invoice_no / order_no / booking_ref / member_code are generated by
--      the application; the database only guarantees they are unique.
--
--  KEY GUARANTEES ENFORCED BY THE DATABASE (not just the app)
--    * Two bookings can never overlap on the same court  (exclusion constraint, section 5)
--    * Max N bookings per member per day (default 2)     (trigger, setting in club_settings)
--    * Social-play sessions cannot exceed their capacity (trigger)
--    * Shop stock can never go negative; counter and online sales hit the same stock row
--    * Exactly one owner and one manager                 (unique indexes, section 1)
--    * A member cannot hold two overlapping memberships  (exclusion constraint, section 4)
--    * invoice.amount_paid / status follow the payments  (trigger, section 10)
--    * A payment can never be refunded for more than it was (trigger, section 10)
--
--  ASSUMPTIONS TO CONFIRM  (search for "ASSUMPTION" in this file)
--    A1 Juniors (under 18) need a guardian record.
--    A2 Both exclusive and social-play bookings count toward the 2-per-day limit.
--    A3 Prices are tax-exclusive; tax rates are GST-style placeholders.
--    A4 Currency INR, timezone Asia/Kolkata (UPI is mentioned in the statement).
--    A5 Sports list contains tennis, padel, badminton AND cricket because the problem
--       statement mentions both sets - keep only what the club offers.
-- =====================================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- needed for the "no overlap" exclusion constraints

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END $$ LANGUAGE plpgsql;


-- =====================================================================================
-- 1. IDENTITY & ACCESS
-- =====================================================================================

CREATE TABLE roles (
    id          smallint PRIMARY KEY,                 -- fixed ids, see seed data (section 14)
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,
    description text
);

CREATE TABLE permissions (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,                 -- 'module.action', e.g. 'booking.manage'
    module      text NOT NULL,
    description text
);

CREATE TABLE role_permissions (
    role_id       smallint NOT NULL REFERENCES roles(id)       ON DELETE CASCADE,
    permission_id bigint   NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

-- One login account per person: staff AND members who use the website/app.
CREATE TABLE users (
    id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name            text NOT NULL,
    email                text,
    phone                text,
    password_hash        text NOT NULL,
    status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','disabled')),
    must_change_password boolean NOT NULL DEFAULT false,
    failed_login_count   smallint NOT NULL DEFAULT 0,
    locked_until         timestamptz,
    last_login_at        timestamptz,
    email_verified_at    timestamptz,
    phone_verified_at    timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_contact_chk CHECK (email IS NOT NULL OR phone IS NOT NULL)
);
CREATE UNIQUE INDEX uq_users_email ON users (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX uq_users_phone ON users (phone)        WHERE phone IS NOT NULL;

-- A user can hold more than one role (e.g. front_desk + accountant in a small club).
CREATE TABLE user_roles (
    user_id     bigint   NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id     smallint NOT NULL REFERENCES roles(id),
    assigned_by bigint   REFERENCES users(id),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);
-- Exactly one owner and exactly one manager (role ids 1 and 2).
-- To allow several managers later, just DROP INDEX uq_single_manager;
CREATE UNIQUE INDEX uq_single_owner   ON user_roles ((true)) WHERE role_id = 1;
CREATE UNIQUE INDEX uq_single_manager ON user_roles ((true)) WHERE role_id = 2;


-- =====================================================================================
-- 2. CLUB PROFILE & SETTINGS   (feeds the public website and the booking rules)
-- =====================================================================================

CREATE TABLE club_profile (                           -- always exactly one row
    id            smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    name          text NOT NULL,
    tagline       text,
    description   text,
    address_line1 text,
    address_line2 text,
    city          text,
    state         text,
    postal_code   text,
    country       text NOT NULL DEFAULT 'IN',
    latitude      numeric(9,6),                        -- "find a place to play near me"
    longitude     numeric(9,6),
    phone         text,
    email         text,
    website_url   text,
    logo_url      text,
    tax_id        text,                                -- GSTIN / VAT number printed on invoices
    currency_code char(3) NOT NULL DEFAULT 'INR',      -- ASSUMPTION A4
    timezone      text NOT NULL DEFAULT 'Asia/Kolkata',
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE club_settings (                          -- business rules the admin can change
    key         text PRIMARY KEY,
    value       text NOT NULL,
    description text,
    updated_by  bigint REFERENCES users(id),
    updated_at  timestamptz NOT NULL DEFAULT now()
);


-- =====================================================================================
-- 3. STAFF (HR): employees, shifts, attendance, leave, payroll
-- =====================================================================================

CREATE TABLE employees (
    id                     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_code          text NOT NULL UNIQUE,
    user_id                bigint UNIQUE REFERENCES users(id),   -- their login (NULL if none)
    full_name              text NOT NULL,
    phone                  text NOT NULL,
    email                  text,
    date_of_birth          date,
    address                text,
    emergency_contact_name  text,
    emergency_contact_phone text,
    department             text NOT NULL CHECK (department IN
                              ('management','front_desk','shop','bar','kitchen','finance','admin')),
    job_title              text NOT NULL,
    employment_type        text NOT NULL DEFAULT 'full_time'
                              CHECK (employment_type IN ('full_time','part_time','casual')),
    hire_date              date NOT NULL,
    termination_date       date,
    status                 text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','terminated')),
    reports_to_employee_id bigint REFERENCES employees(id),      -- leave/shift approver (the manager)
    pay_type               text NOT NULL DEFAULT 'monthly' CHECK (pay_type IN ('monthly','hourly')),
    base_salary            numeric(12,2) CHECK (base_salary >= 0),   -- per month
    hourly_rate            numeric(10,2) CHECK (hourly_rate >= 0),
    tax_id                 text,                                 -- PAN etc., for tax deducted at source
    bank_account_holder    text,
    bank_name              text,
    bank_account_number    text,                                 -- encrypt at application level
    bank_ifsc              text,
    notes                  text,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CHECK (termination_date IS NULL OR termination_date >= hire_date),
    CHECK ((pay_type = 'monthly' AND base_salary IS NOT NULL) OR (pay_type = 'hourly' AND hourly_rate IS NOT NULL))
);

CREATE TABLE shift_templates (                        -- reusable patterns: Morning, Evening, Closing
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    department text CHECK (department IN ('management','front_desk','shop','bar','kitchen','finance','admin')),
    start_time time NOT NULL,
    end_time   time NOT NULL,
    is_active  boolean NOT NULL DEFAULT true
);

CREATE TABLE shifts (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employees(id),
    department  text NOT NULL CHECK (department IN ('management','front_desk','shop','bar','kitchen','finance','admin')),
    template_id bigint REFERENCES shift_templates(id),
    starts_at   timestamptz NOT NULL,
    ends_at     timestamptz NOT NULL,
    status      text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','completed','absent','cancelled')),
    notes       text,
    created_by  bigint REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at),
    -- one person cannot be rostered on two overlapping shifts
    CONSTRAINT shifts_no_overlap EXCLUDE USING gist
        (employee_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (status <> 'cancelled')
);

CREATE TABLE attendance_records (                     -- actual clock-in / clock-out (feeds payroll)
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employees(id),
    shift_id    bigint REFERENCES shifts(id),
    clock_in    timestamptz NOT NULL,
    clock_out   timestamptz,
    method      text NOT NULL DEFAULT 'manual' CHECK (method IN ('manual','qr','biometric','app')),
    notes       text,
    recorded_by bigint REFERENCES users(id),
    CHECK (clock_out IS NULL OR clock_out > clock_in)
);

CREATE TABLE leave_types (
    id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name              text NOT NULL UNIQUE,
    is_paid           boolean NOT NULL DEFAULT true,
    annual_quota_days numeric(4,1) CHECK (annual_quota_days >= 0),    -- NULL = not set / unlimited
    is_active         boolean NOT NULL DEFAULT true
);

CREATE TABLE leave_requests (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id    bigint NOT NULL REFERENCES employees(id),
    leave_type_id  bigint NOT NULL REFERENCES leave_types(id),
    start_date     date NOT NULL,
    end_date       date NOT NULL,
    days_requested numeric(4,1) NOT NULL CHECK (days_requested > 0),
    reason         text,
    status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
    requested_at   timestamptz NOT NULL DEFAULT now(),
    decided_by     bigint REFERENCES users(id),           -- the manager (or owner for the manager's own leave)
    decided_at     timestamptz,
    decision_note  text,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date),
    CHECK (status = 'pending' OR status = 'cancelled' OR decided_by IS NOT NULL)
);

CREATE TABLE payroll_runs (                           -- one run per month
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    period_month date NOT NULL UNIQUE CHECK (extract(day FROM period_month) = 1),   -- first day of month
    status       text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','paid')),
    created_by   bigint REFERENCES users(id),
    approved_by  bigint REFERENCES users(id),
    approved_at  timestamptz,
    paid_at      timestamptz,
    notes        text,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE payroll_items (                          -- one payslip per employee per run
    id                    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payroll_run_id        bigint NOT NULL REFERENCES payroll_runs(id) ON DELETE CASCADE,
    employee_id           bigint NOT NULL REFERENCES employees(id),
    days_worked           numeric(5,1) NOT NULL DEFAULT 0,
    hours_worked          numeric(7,2),
    unpaid_leave_days     numeric(4,1) NOT NULL DEFAULT 0,
    base_pay              numeric(12,2) NOT NULL DEFAULT 0 CHECK (base_pay >= 0),
    overtime_pay          numeric(12,2) NOT NULL DEFAULT 0 CHECK (overtime_pay >= 0),
    allowances            numeric(12,2) NOT NULL DEFAULT 0 CHECK (allowances >= 0),
    gross_pay             numeric(12,2) GENERATED ALWAYS AS (base_pay + overtime_pay + allowances) STORED,
    unpaid_leave_deduction numeric(12,2) NOT NULL DEFAULT 0 CHECK (unpaid_leave_deduction >= 0),
    tax_deducted          numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax_deducted >= 0),
    other_deductions      numeric(12,2) NOT NULL DEFAULT 0 CHECK (other_deductions >= 0),
    net_pay               numeric(12,2) GENERATED ALWAYS AS
                              (base_pay + overtime_pay + allowances
                               - unpaid_leave_deduction - tax_deducted - other_deductions) STORED,
    payment_status        text NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending','paid')),
    paid_at               timestamptz,
    payment_method        text CHECK (payment_method IN ('cash','card','upi','online','bank_transfer','cheque')),
    payment_reference     text,
    UNIQUE (payroll_run_id, employee_id)
);


-- =====================================================================================
-- 4. MEMBERS & CUSTOMERS
-- =====================================================================================

CREATE TABLE guardians (                              -- parent / guardian of a Junior member
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name    text NOT NULL,
    phone        text NOT NULL,
    email        text,
    relationship text,                                 -- mother, father, guardian...
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- The three tiers: Gold (premium, full access), Silver (standard), Junior (under 18, discounted).
CREATE TABLE membership_plans (
    id                    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code                  text NOT NULL UNIQUE,         -- 'gold', 'silver', 'junior'
    name                  text NOT NULL,
    description           text,
    fee                   numeric(10,2) NOT NULL CHECK (fee >= 0),
    duration_months       smallint NOT NULL CHECK (duration_months > 0),
    joining_fee           numeric(10,2) NOT NULL DEFAULT 0 CHECK (joining_fee >= 0),
    min_age               smallint CHECK (min_age >= 0),
    max_age               smallint,                     -- Junior: 17
    shop_discount_pct     numeric(5,2) NOT NULL DEFAULT 0 CHECK (shop_discount_pct BETWEEN 0 AND 100),
    bar_discount_pct      numeric(5,2) NOT NULL DEFAULT 0 CHECK (bar_discount_pct  BETWEEN 0 AND 100),
    can_join_social_play  boolean NOT NULL DEFAULT true,
    is_active             boolean NOT NULL DEFAULT true,
    sort_order            smallint NOT NULL DEFAULT 0,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CHECK (min_age IS NULL OR max_age IS NULL OR max_age >= min_age)
);
-- Court prices per plan (free / discounted / walk-in) live in court_rates (section 5).

CREATE TABLE plan_benefits (                          -- bullet points for the website / plan comparison
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    plan_id     bigint NOT NULL REFERENCES membership_plans(id) ON DELETE CASCADE,
    description text NOT NULL,
    sort_order  smallint NOT NULL DEFAULT 0
);

CREATE TABLE members (
    id                      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_code             text NOT NULL UNIQUE,        -- number on the card; what staff type at the desk
    qr_token                text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text, '-', ''),
    user_id                 bigint UNIQUE REFERENCES users(id),   -- online login (NULL = desk-only member)
    full_name               text NOT NULL,
    date_of_birth           date NOT NULL CHECK (date_of_birth <= current_date),
    phone                   text NOT NULL,
    email                   text,
    address_line1           text,
    address_line2           text,
    city                    text,
    postal_code             text,
    photo_url               text,                        -- so staff can recognise them quickly
    emergency_contact_name  text,
    emergency_contact_phone text,
    guardian_id             bigint REFERENCES guardians(id),
    status                  text NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','left')),
    joined_on               date NOT NULL DEFAULT current_date,
    registered_by           bigint REFERENCES users(id), -- front-desk user who signed them up
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    -- ASSUMPTION A1: anyone under 18 must have a guardian on file
    CONSTRAINT members_minor_needs_guardian
        CHECK (guardian_id IS NOT NULL OR date_of_birth <= current_date - interval '18 years')
);

-- A member's plan over time. Renewal, upgrade, downgrade = a NEW row linked to the previous one.
CREATE TABLE memberships (
    id                     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_id              bigint NOT NULL REFERENCES members(id),
    plan_id                bigint NOT NULL REFERENCES membership_plans(id),
    start_date             date NOT NULL,
    end_date               date NOT NULL,               -- expiry; reminders are driven by this
    status                 text NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending','active','expired','cancelled','changed')),
                           -- 'changed' = replaced by a different plan before its end date
    started_as             text NOT NULL DEFAULT 'new' CHECK (started_as IN ('new','renewal','upgrade','downgrade')),
    previous_membership_id bigint REFERENCES memberships(id),
    auto_renew             boolean NOT NULL DEFAULT false,
    fee_charged            numeric(10,2) NOT NULL CHECK (fee_charged >= 0),        -- snapshot of plan fee
    joining_fee_charged    numeric(10,2) NOT NULL DEFAULT 0 CHECK (joining_fee_charged >= 0),
    cancelled_at           timestamptz,
    cancelled_by           bigint REFERENCES users(id),
    cancellation_reason    text,
    created_by             bigint REFERENCES users(id),
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date),
    CONSTRAINT memberships_no_overlap EXCLUDE USING gist
        (member_id WITH =, daterange(start_date, end_date, '[]') WITH &&)
        WHERE (status IN ('pending','active'))
);

CREATE TABLE guests (                                 -- walk-ins / non-members who pay the walk-in rate
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name           text NOT NULL,
    phone               text,
    email               text,
    source              text NOT NULL DEFAULT 'walk_in' CHECK (source IN ('walk_in','phone','website','bar')),
    converted_member_id bigint REFERENCES members(id),   -- set when a guest later joins
    notes               text,
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE business_clients (                       -- companies the club invoices
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    company_name        text NOT NULL,
    contact_person      text,
    email               text,
    phone               text,
    billing_address1    text,
    billing_address2    text,
    city                text,
    state               text,
    postal_code         text,
    tax_id              text,                          -- client GSTIN
    payment_terms_days  smallint NOT NULL DEFAULT 15 CHECK (payment_terms_days >= 0),
    status              text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    notes               text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE member_notes (                           -- staff notes shown on the member's profile
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_id  bigint NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    note       text NOT NULL,
    is_pinned  boolean NOT NULL DEFAULT false,
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);


-- =====================================================================================
-- 5. COURTS & BOOKINGS
-- =====================================================================================

CREATE TABLE sports (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name      text NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE courts (
    id                    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name                  text NOT NULL UNIQUE,         -- 'Court 1', 'Padel A'
    sport_id              bigint NOT NULL REFERENCES sports(id),
    surface               text,                         -- clay, hard, synthetic, turf...
    is_indoor             boolean NOT NULL DEFAULT false,
    social_play_capacity  smallint CHECK (social_play_capacity > 0),   -- default people per court in social play
    status                text NOT NULL DEFAULT 'active' CHECK (status IN ('active','maintenance','closed')),
    notes                 text,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE court_operating_hours (                  -- when each court can be booked
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    court_id    bigint NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
    day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    open_time   time NOT NULL,
    close_time  time NOT NULL,
    UNIQUE (court_id, day_of_week),
    CHECK (close_time > open_time)
);

-- Price list. plan_id NULL = walk-in / non-member rate. price 0 = free (e.g. Gold).
CREATE TABLE court_rates (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sport_id     bigint NOT NULL REFERENCES sports(id),
    plan_id      bigint REFERENCES membership_plans(id),
    applies_to   text NOT NULL DEFAULT 'exclusive_booking'
                    CHECK (applies_to IN ('exclusive_booking','social_play_per_person')),
    days_of_week smallint[] CHECK (days_of_week IS NULL OR days_of_week <@ ARRAY[0,1,2,3,4,5,6]::smallint[]),
    start_time   time,                                  -- optional peak / off-peak band
    end_time     time,
    price        numeric(10,2) NOT NULL CHECK (price >= 0),   -- per session (or per person for social play)
    valid_from   date NOT NULL DEFAULT current_date,
    valid_to     date,
    is_active    boolean NOT NULL DEFAULT true,
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CHECK ((start_time IS NULL) = (end_time IS NULL))
);

-- The physical occupancy of a court. THIS is what must never overlap.
--   exclusive : one booking owns the court for the session
--   social    : many people share the court (Friday-night social play)
--   blocked   : maintenance, tournament, private hire
CREATE TABLE court_reservations (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    court_id         bigint NOT NULL REFERENCES courts(id),
    starts_at        timestamptz NOT NULL,
    ends_at          timestamptz NOT NULL,
    reservation_type text NOT NULL CHECK (reservation_type IN ('exclusive','social','blocked')),
    status           text NOT NULL DEFAULT 'active' CHECK (status IN ('active','cancelled')),
    social_title     text,                              -- 'Friday Night Social'
    social_capacity  smallint CHECK (social_capacity > 0),
    block_reason     text,
    created_by       bigint REFERENCES users(id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at),
    CHECK ((reservation_type = 'social') = (social_capacity IS NOT NULL)),
    UNIQUE (id, reservation_type),
    CONSTRAINT court_no_double_booking EXCLUDE USING gist
        (court_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (status = 'active')
    -- session length (60 min) and slot start (:00 / :30) come from club_settings and are
    -- validated by the application, so the club can change them without a schema change.
);

-- A person's booking on a reservation. Exclusive reservation = one booking; social = many.
CREATE TABLE bookings (
    id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    booking_ref       text NOT NULL UNIQUE,
    reservation_id    bigint NOT NULL,
    reservation_type  text NOT NULL CHECK (reservation_type IN ('exclusive','social')),
    member_id         bigint REFERENCES members(id),
    guest_id          bigint REFERENCES guests(id),
    membership_id     bigint REFERENCES memberships(id),   -- the plan in force when booked
    booked_via        text NOT NULL CHECK (booked_via IN ('member_app','website','front_desk','phone','walk_in')),
    booked_by         bigint REFERENCES users(id),         -- who made it (member, receptionist; NULL for public visitor)
    is_trial          boolean NOT NULL DEFAULT false,      -- trial session booked from the website
    rate_id           bigint REFERENCES court_rates(id),
    price_basis       text NOT NULL DEFAULT 'walk_in_rate'
                         CHECK (price_basis IN ('member_rate','walk_in_rate','plan_included','trial','complimentary')),
    amount_charged    numeric(10,2) NOT NULL DEFAULT 0 CHECK (amount_charged >= 0),   -- 0 = free for this plan
    status            text NOT NULL DEFAULT 'confirmed'
                         CHECK (status IN ('confirmed','checked_in','completed','cancelled','no_show')),
    checked_in_at     timestamptz,
    cancelled_at      timestamptz,
    cancelled_by      bigint REFERENCES users(id),
    cancellation_reason text,
