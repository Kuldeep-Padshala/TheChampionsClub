-- Booking rules enforced in the database -------------------------------------------------
CREATE OR REPLACE FUNCTION fn_bookings_before_insert() RETURNS trigger AS $$
DECLARE
    v_capacity smallint;
    v_day      date;
    v_tz       text;
    v_limit    int;
    v_count    int;
BEGIN
    IF NEW.status = 'cancelled' THEN
        RETURN NEW;
    END IF;

    SELECT COALESCE((SELECT timezone FROM club_profile LIMIT 1), 'UTC') INTO v_tz;

    -- lock the reservation row so two simultaneous bookings are processed one after the other
    SELECT r.social_capacity, (r.starts_at AT TIME ZONE v_tz)::date
      INTO v_capacity, v_day
      FROM court_reservations r
     WHERE r.id = NEW.reservation_id
       FOR UPDATE;

    -- (a) social play: never more people than the session capacity
    IF NEW.reservation_type = 'social' THEN
        SELECT count(*) INTO v_count
          FROM bookings b
         WHERE b.reservation_id = NEW.reservation_id AND b.status <> 'cancelled';
        IF v_count >= v_capacity THEN
            RAISE EXCEPTION 'Social session is full (capacity %)', v_capacity USING ERRCODE = '23514';
        END IF;
    END IF;

    -- (b) a member can play at most N times a day (ASSUMPTION A2: social play counts too)
    IF NEW.member_id IS NOT NULL THEN
        SELECT NULLIF(value, '')::int INTO v_limit
          FROM club_settings WHERE key = 'max_bookings_per_member_per_day';
        IF v_limit IS NOT NULL THEN
            PERFORM pg_advisory_xact_lock(hashtextextended('booking_limit:' || NEW.member_id, 0));
            SELECT count(*) INTO v_count
              FROM bookings b
              JOIN court_reservations r ON r.id = b.reservation_id
             WHERE b.member_id = NEW.member_id
               AND b.status <> 'cancelled'
               AND (r.starts_at AT TIME ZONE v_tz)::date = v_day;
            IF v_count >= v_limit THEN
                RAISE EXCEPTION 'Member % already has % booking(s) on % (daily limit %)',
                    NEW.member_id, v_count, v_day, v_limit USING ERRCODE = '23514';
            END IF;
        END IF;
    END IF;

    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_bookings_before_insert
    BEFORE INSERT ON bookings FOR EACH ROW EXECUTE FUNCTION fn_bookings_before_insert();

-- When an exclusive booking is cancelled, free the court straight away.
CREATE OR REPLACE FUNCTION fn_release_court_on_cancel() RETURNS trigger AS $$
BEGIN
    IF NEW.reservation_type = 'exclusive' AND NEW.status = 'cancelled' AND OLD.status <> 'cancelled' THEN
        UPDATE court_reservations SET status = 'cancelled' WHERE id = NEW.reservation_id;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_bookings_release_court
    AFTER UPDATE OF status ON bookings FOR EACH ROW EXECUTE FUNCTION fn_release_court_on_cancel();


