    tax_credit         numeric(12,2) NOT NULL DEFAULT 0,   -- on purchases / expenses
    net_payable        numeric(12,2) GENERATED ALWAYS AS (tax_collected - tax_credit) STORED,
    status             VARCHAR(255) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','filed','paid')),
    due_date           date,
    filed_at           DATETIME,
    filed_by           bigint REFERENCES users(id),
    paid_at            DATETIME,
    reference_no       VARCHAR(255),
    notes              VARCHAR(255),
    created_by         bigint REFERENCES users(id),
    created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (period_end >= period_start)
);

CREATE TABLE report_shares (                            -- owner shares "the numbers" with a partner, bank, accountant
    id              bigint AUTO_INCREMENT PRIMARY KEY,
    report_type     VARCHAR(255) NOT NULL CHECK (report_type IN
                       ('daily_summary','weekly_summary','monthly_summary','revenue_by_source','payables','tax_summary','custom')),
    period_start    date NOT NULL,
    period_end      date NOT NULL,
    snapshot        JSON NOT NULL,                      -- the figures frozen at the moment of sharing
    share_token     VARCHAR(255) NOT NULL UNIQUE DEFAULT (REPLACE(UUID(), '-', '')),
    recipient_name  VARCHAR(255),
    recipient_email VARCHAR(255),
    expires_at      DATETIME,
    revoked_at      DATETIME,
    view_count      integer NOT NULL DEFAULT 0,
    created_by      bigint NOT NULL REFERENCES users(id),
    created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (period_end >= period_start)
);


