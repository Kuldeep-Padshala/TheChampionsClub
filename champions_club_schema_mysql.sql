CREATE TABLE notifications (
    id                bigint AUTO_INCREMENT PRIMARY KEY,
    recipient_user_id bigint REFERENCES users(id),
    recipient_contact VARCHAR(255),                              -- email / phone for someone without a login
    type              VARCHAR(255) NOT NULL,                     -- enquiry_new, membership_expiring, low_stock,
                                                         -- leave_requested, leave_decided, order_ready, booking_confirmed...
    channel           VARCHAR(255) NOT NULL DEFAULT 'in_app' CHECK (channel IN ('in_app','email','sms','whatsapp','push')),
    title             VARCHAR(255) NOT NULL,
    body              VARCHAR(255),
    entity_type       VARCHAR(255),                              -- what it is about, e.g. 'membership'
    entity_id         bigint,
    dedupe_key        VARCHAR(255) UNIQUE,                       -- e.g. 'membership_expiry:42:7d' so a reminder is sent once
    status            VARCHAR(255) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','failed')),
    is_read           boolean NOT NULL DEFAULT false,
    read_at           DATETIME,
    scheduled_for     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at           DATETIME,
    created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (recipient_user_id IS NOT NULL OR recipient_contact IS NOT NULL)
);

CREATE TABLE audit_logs (                               -- who changed what (money, prices, roles, stock)
    id          bigint AUTO_INCREMENT PRIMARY KEY,
    user_id     bigint REFERENCES users(id),
    action      VARCHAR(255) NOT NULL,                           -- 'create', 'update', 'delete', 'login', 'refund', 'void'...
    entity_type VARCHAR(255) NOT NULL,
    entity_id   bigint,
    old_values  JSON,
    new_values  JSON,
    ip_address  VARCHAR(45),
    user_agent  VARCHAR(255),
    created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);


