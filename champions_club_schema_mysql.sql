-- One invoice table for everything: counter receipts, bar bills, court fees, memberships,
-- and invoices to business clients. Each LINE says which part of the club earned it.
CREATE TABLE invoices (
    id                 bigint AUTO_INCREMENT PRIMARY KEY,
    invoice_no         VARCHAR(255) NOT NULL UNIQUE,
    member_id          bigint REFERENCES members(id),
    guest_id           bigint REFERENCES guests(id),
    business_client_id bigint REFERENCES business_clients(id),
    bill_to_name       VARCHAR(255),                              -- snapshot name printed on the invoice
    quote_id           bigint REFERENCES quotes(id),
    status             VARCHAR(255) NOT NULL DEFAULT 'draft'
                          CHECK (status IN ('draft','issued','partially_paid','paid','void')),
    issue_date         date NOT NULL DEFAULT (CURDATE()),
    due_date           date,                              -- overdue = issued/partially_paid and due_date < today
    subtotal           numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_total     numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    tax_total          numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    total_amount       numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    amount_paid        numeric(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),   -- kept in sync by trigger
    balance_due        numeric(12,2) GENERATED ALWAYS AS (total_amount - amount_paid) STORED,
    notes              VARCHAR(255),
    issued_by          bigint REFERENCES users(id),
    voided_at          DATETIME,
    voided_by          bigint REFERENCES users(id),
    void_reason        VARCHAR(255),
    created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (((member_id IS NOT NULL) + (guest_id IS NOT NULL) + (business_client_id IS NOT NULL)) <= 1)
);

CREATE TABLE invoice_items (
    id              bigint AUTO_INCREMENT PRIMARY KEY,
    invoice_id      bigint NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    source          VARCHAR(255) NOT NULL CHECK (source IN ('membership','court_booking','shop','bar','other')),  -- "from where"
    description     VARCHAR(255) NOT NULL,
    quantity        numeric(10,2) NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price      numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_rate_id     bigint REFERENCES tax_rates(id),
    tax_amount      numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    line_total      numeric(12,2) NOT NULL CHECK (line_total >= 0),       -- includes tax
    -- what this line bills (at most one):
    membership_id   bigint REFERENCES memberships(id),
    booking_id      bigint REFERENCES bookings(id),
    shop_order_id   bigint REFERENCES shop_orders(id),
    bar_order_id    bigint REFERENCES bar_orders(id),                     -- a tab settles as one line per order
    CHECK (((membership_id IS NOT NULL) + (booking_id IS NOT NULL) + (shop_order_id IS NOT NULL) + (bar_order_id IS NOT NULL)) <= 1),
    CHECK (membership_id IS NULL OR source = 'membership'),
    CHECK (booking_id    IS NULL OR source = 'court_booking'),
    CHECK (shop_order_id IS NULL OR source = 'shop'),
    CHECK (bar_order_id  IS NULL OR source = 'bar')
);

